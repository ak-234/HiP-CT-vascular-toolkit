from __future__ import annotations
import csv
from pathlib import Path
from types import SimpleNamespace
rbc = SimpleNamespace(MMHG_TO_PA=133.322)
PHI = 0.45
MMHG_MONITOR = 133.322
INLET_NAME, OUTLET_NAME, WALL_NAME = "Inlet", "Outlet{k}", "Wall"
MATERIAL_NAME, FLUID_NAME = "Blood", "Blood Fluid"
WK_ARGUMENT_UNITS = "[],[s],[Pa s/m^3],[Pa s/m^3],[m^3/Pa],[Pa],[m^3/s],[Pa]"
USER_ROUTINES = (
    ("jbpandq", "jbpandq", "jbpandq", "Start of Time Step"),
    ("jbqpast", "jbqpast", "jbqpast", "End of Time Step"),
    ("windkessel", "windk", "windkessel", None),
)

def read_waveform_csv(path: str | Path, n_harmonics: int) -> tuple[list[float], list[float]]:
    """``a_k``, ``b_k`` (m^3/s) of the inflow Fourier series from a CSV with columns ``a`` and
    ``b`` (an optional ``k`` column orders them; without it rows are k = 0, 1, 2 ...). Missing
    harmonics are zero, extra ones beyond ``n_harmonics`` are dropped with a warning."""
    a = [0.0] * (n_harmonics + 1)
    b = [0.0] * (n_harmonics + 1)
    with open(path, newline="") as f:
        reader = csv.DictReader(f)
        fields = {(h or "").strip().lower(): h for h in (reader.fieldnames or [])}
        if "a" not in fields or "b" not in fields:
            raise SystemExit(f"[ERROR] {path}: the waveform CSV needs 'a' and 'b' columns (m^3/s).")
        for i, row in enumerate(reader):
            k = int(float(row[fields["k"]])) if "k" in fields and row.get(fields["k"]) else i
            if k > n_harmonics:
                print(f"[WARN] {path}: harmonic {k} dropped (--n-harmonics {n_harmonics})")
                continue
            a[k] = float(row[fields["a"]] or 0.0)
            b[k] = float(row[fields["b"]] or 0.0)
    return a, b


def waveform_ccl_lines(a: list[float], b: list[float], period: float) -> list[str]:
    """The template's inflow Fourier block: ``a<k>``, ``b<k>``, ``f0`` and ``vin`` (m^3/s)."""
    n = len(a) - 1
    lines = []
    for k in range(n + 1):
        lines.append(f"      a{k} = {a[k]:.17e} [m^3/s]")
    for k in range(n + 1):
        lines.append(f"      b{k} = {b[k]:.17e} [m^3/s]")
    lines.append(f"      f0 = {1.0 / period:.6f} [s^-1]")
    terms = ["a0"]
    for k in range(1, n + 1):
        terms.append(f"+a{k}*cos(-2*pi*{k}*f0*t) +b{k}*sin(-2*pi*{k}*f0*t)")
    # one term per line, continued with CCL's trailing backslash
    lines.append("      vin = " + " \\\n        ".join(terms))
    return lines


def generate_windkessel_ccl(outs: list[dict], inlet: dict, params: dict,
                            out_path: str | Path) -> Path:
    """Write the complete CFX-Pre CCL for one tree with 3-EWM outlets.

    Block for block the layout of the template case (``CFX/Case_1.cfx``, exported with CFX-Pre):
    USER block; CEL with the blood constants, the Quemada expression, the Windkessel
    parameters, the outlet/inlet monitors and the inflow waveform (``a<k>``/``b<k>`` Fourier
    terms, ``vin``, ``vinlet``, ``vconstant``, ``period``, ``Tcycle``, ``numCycle``, ``SaveT``);
    the ``WK`` user function; the ``Blood`` material; the three user routines; a transient Flow
    Analysis whose domain holds the ``Inlet`` (normal speed), the ``Outlet<k>`` OPENINGs driven by
    ``WK()``, an explicit ``Wall``, the models and the initialisation; monitor points; and the
    solver control the routines need. Only the DOMAIN ``Location`` and the wall's ``Location``
    are left for ``cfx_def_export.py``, which reads them from the mesh.
    """
    rho = params["rho"]
    dt = params["delta_t"]
    lib_dir = Path(params["user_lib_dir"])
    n = len(outs)
    q_total = outs[0]["q_total_rest"]
    p_ao, p_d = params["p_aortic_mmHg"], params["p_distal_mmHg"]
    p_init = params.get("p_init_pa") or 0.0
    period, num_cycles = params["period"], params["num_cycles"]
    wave_a, wave_b = params["waveform"]
    lines: list[str] = []

    lines.append("# ============================================================")
    lines.append(f"# {params['title']}")
    lines.append(f"# Generated by windkessel_BC.py from {params['source_file']}")
    lines.append(f"# Fluid density Rho = {rho:g} kg/m^3")
    lines.append(f"# P_mean_aortic = {p_ao:g} mmHg, P_distal = {p_d:g} mmHg, "
                 f"design dP = {(p_ao - p_d) * rbc.MMHG_TO_PA:.1f} Pa")
    lines.append("# Explicit Rp, Rd and C supplied by coronary-rcr; no parameter recalculation.")
    for note in params.get("header_note", []):
        lines.append(f"# {note}")
    lines.append("# Layout follows the CFX template case (Case_1.cfx): Blood material, Inlet as a normal")
    lines.append("# speed (vconstant = Q_total/area; --pulsatile switches to the Fourier waveform vinlet),")
    lines.append(f"# {num_cycles} cycles of {period:g} s, results every cycle then every {params['save_last']:g} s in the last.")
    lines.append("# Outlets are named Outlet<k> because the jbpandq junction box looks them up by that")
    lines.append("# name (USER: NOUTLET); the pipeline name of each zone is in the trailing comment.")
    lines.append("# PRESSURE DATUM: capacitor and distal pressures use the same CFX gauge datum.")
    lines.append("# The DOMAIN and Wall Locations are filled in by cfx_def_export.py from the .msh.")
    lines.append(f"# User-Fortran libraries: {lib_dir}\\<routine>\\winnt-amd64  (cfx_user_fortran/README.md)")
    lines.append("# ============================================================\n")

    # ---- USER block read by the junction boxes ----
    lines.append("USER:")
    lines.append(f"  DENSITY = {rho:g}")
    lines.append(f"  NOUTLET = {n}")
    lines.append(f"  RCR_STEP = {params.get('step_offset', 0)}")
    lines.append(f"  RCR_DT = {dt:.17g}")
    for o in outs:
        lines.append(f"  RCR_PC_{o['k']} = {o['pc0_pa']:.17g}")
        lines.append(f"  RCR_Q_{o['k']} = {o['q_i']:.17g}")
        lines.append(f"  RCR_RD_{o['k']} = {o['R2']:.17g}")
        lines.append(f"  RCR_C_{o['k']} = {o['C']:.17g}")
        lines.append(f"  RCR_PV_{o['k']} = {o['pv_pa']:.17g}")
    lines.append("END")

    # ---- LIBRARY: CEL, WK function, material, user routines ----
    lines.append("LIBRARY:")
    lines.append("  CEL:")
    lines.append("    EXPRESSIONS:")
    lines.append(f"      BloodDens = {rho:g} [kg/m^3]")
    lines.append("      BloodViscosity = muF*(1-0.5*Phi*(k0+kinf*sqrt(gr))/(1+sqrt(gr)))^(-2)")
    lines.append("      # Windkessel parameters: R1 characteristic impedance, R2 peripheral resistance, C compliance")
    for o in outs:
        k = o["k"]
        tag = (f"{o['ccl_name']}  r={o['radius_mm']:.4f}mm A={o['area_mm2']:.4f}mm2 "
               f"c={o['c']:.3f}m/s R_T={o['R_T']:.17e}")
        lines.append(f"      CA{k:02d} = {o['C']:.17e} [m^4 s^2 kg^-1] # {tag}")
    lines.append(f"      DeltaT = {dt:g} [s]")
    lines.append(f"      Phi = {PHI:g}")
    lines.append(f"      Pinlet = ave(Pressure)@{INLET_NAME}")
    lines.append("      # Outlet pressure / flow monitors (outflow positive, matching jbpandq)")
    for o in outs:
        lines.append(f"      Pout{o['k']:02d} = ave(Pressure)@{OUTLET_NAME.format(k=o['k'])}")
    for o in outs:
        lines.append(f"      Qfuture{o['k']:02d} = ({MATERIAL_NAME}.massFlow()@{OUTLET_NAME.format(k=o['k'])} * -1) / BloodDens")
    lines.append(f"      Qinlet = ({MATERIAL_NAME}.massFlow()@{INLET_NAME}) / BloodDens")
    for o in outs:
        lines.append(f"      R1A{o['k']:02d} = {o['R1']:.17e} [kg m^-4 s^-1]")
    for o in outs:
        lines.append(f"      R2A{o['k']:02d} = {o['R2']:.17e} [kg m^-4 s^-1]")
    lines.append(f"      SaveT = if( t < (numCycle-1)*Tcycle, Tcycle, {params['save_last']:g}[s])")
    lines.append(f"      Tcycle = {period:g} [s]")
    lines.append("      # Inflow waveform: Fourier series vin(t) in m^3/s (a0 = mean flow); the Inlet uses")
    lines.append("      # vconstant (steady Q_total) unless the CCL was written with --pulsatile")
    lines.extend(waveform_ccl_lines(wave_a, wave_b, period))
    lines.append("      gr = Shear Strain Rate /grc")
    lines.append("      grc = 2.3 [s^-1]")
    lines.append("      k0 = 3.691")
    lines.append("      kinf = 1.778")
    lines.append("      muF = 1.32e-3 [Pa s]")
    lines.append(f"      numCycle = {num_cycles}")
    lines.append(f"      period = {period:g} [s]")
    lines.append("      v0 = 2*pi/period")
    lines.append(f"      vconstant = {q_total:.17e} [m^3 s^-1] / area@{INLET_NAME}"
                 f" # = Q_total ({q_total * 6e7:.2f} mL/min)")
    lines.append(f"      vinlet = vin/area()@{INLET_NAME}")
    lines.append("    END")
    lines.append("    FUNCTION: WK")
    lines.append(f"      Argument Units = {WK_ARGUMENT_UNITS}")
    lines.append("      Option = User Function")
    lines.append("      Result Units = [Pa]")
    lines.append("      User Routine Name = windkessel")
    lines.append("    END")
    lines.append("  END")
    lines.append(f"  MATERIAL: {MATERIAL_NAME}")
    lines.append("    Material Description = Quemada Non-Newtonian Blood Model")
    lines.append("    Material Group = User")
    lines.append("    Option = Pure Substance")
    lines.append("    Thermodynamic State = Liquid")
    lines.append("    PROPERTIES:")
    lines.append("      Option = General Material")
    lines.append("      EQUATION OF STATE:")
    lines.append("        Density = BloodDens")
    lines.append("        Molar Mass = 1 [kg kmol^-1]")
    lines.append("        Option = Value")
    lines.append("      END")
    lines.append("      DYNAMIC VISCOSITY:")
    if params["viscosity"] == "quemada":
        lines.append("        Dynamic Viscosity = BloodViscosity")
    else:
        lines.append(f"        Dynamic Viscosity = {params['mu']:g} [Pa s]")
    lines.append("        Option = Value")
    lines.append("      END")
    lines.append("    END")
    lines.append("  END")
    lines.append("  USER ROUTINE DEFINITIONS:")
    for ccl_name, folder, libname, jb_loc in USER_ROUTINES:
        lines.append(f"    USER ROUTINE: {ccl_name}")
        lines.append(f"      Calling Name = {libname}")
        if jb_loc:
            lines.append(f"      Junction Box Location = {jb_loc}")
        lines.append(f"      Library Name = {libname}")
        lines.append(f"      Library Path = {lib_dir / folder}")
        lines.append(f"      Option = {'Junction Box Routine' if jb_loc else 'User CEL Function'}")
        lines.append("    END")
    lines.append("  END")
    lines.append("END")

    # ---- FLOW ----
    lines.append("FLOW: Flow Analysis 1")
    lines.append("  SOLUTION UNITS:")
    lines.append("    Angle Units = [rad]")
    lines.append("    Length Units = [m]")
    lines.append("    Mass Units = [kg]")
    lines.append("    Solid Angle Units = [sr]")
    lines.append("    Temperature Units = [K]")
    lines.append("    Time Units = [s]")
    lines.append("  END")
    lines.append("  ANALYSIS TYPE:")
    lines.append("    Option = Transient")
    lines.append("    EXTERNAL SOLVER COUPLING:")
    lines.append("      Option = None")
    lines.append("    END")
    lines.append("    INITIAL TIME:")
    lines.append("      Option = Automatic with Value")
    lines.append(f"      Time = {params.get('initial_time_s', 0.0):.17g} [s]")
    lines.append("    END")
    lines.append("    TIME DURATION:")
    lines.append("      Option = Total Time")
    lines.append(f"      Total Time = {params.get('initial_time_s', 0.0):.17g} [s] + numCycle*period")
    lines.append("    END")
    lines.append("    TIME STEPS:")
    lines.append("      Option = Timesteps")
    lines.append(f"      Timesteps = {dt:g} [s]")
    lines.append("    END")
    lines.append("  END")
    lines.append(f"  DOMAIN: {params['domain']}")
    lines.append("    Coord Frame = Coord 0")
    lines.append("    Domain Type = Fluid")

    # ---- INLET: normal speed from Q_total (or the waveform) ----
    inlet_comment = (" # PLACEHOLDER - rename to the mesh inlet zone" if inlet.get("placeholder")
                     else f" # pipeline name: {inlet.get('name', '')}")
    lines.append(f"    BOUNDARY: {INLET_NAME}")
    lines.append("      Boundary Type = INLET")
    lines.append(f"      Location = {inlet['location']}{inlet_comment}")
    lines.append("      BOUNDARY CONDITIONS:")
    lines.append("        FLOW REGIME:")
    lines.append("          Option = Subsonic")
    lines.append("        END")
    lines.append("        MASS AND MOMENTUM:")
    lines.append(f"          Normal Speed = {'vinlet' if params['pulsatile'] else 'vconstant'}"
                 f" # Rho*Q_total = {rho * q_total:.17e} kg/s")
    lines.append("          Option = Normal Speed")
    lines.append("        END")
    lines.append("      END")
    lines.append("    END")

    # ---- OUTLETS: OPENING driven by WK() ----
    for o in outs:
        k = o["k"]
        lines.append(f"    BOUNDARY: {OUTLET_NAME.format(k=k)}")
        lines.append("      Boundary Type = OPENING")
        lines.append(f"      Location = {o['region_name']} # {o['ccl_name']}  frac={o['fraction']:.6f}")
        lines.append("      BOUNDARY CONDITIONS:")
        lines.append("        FLOW DIRECTION:")
        lines.append("          Option = Normal to Boundary Condition")
        lines.append("        END")
        lines.append("        FLOW REGIME:")
        lines.append("          Option = Subsonic")
        lines.append("        END")
        lines.append("        MASS AND MOMENTUM:")
        lines.append("          Option = Opening Pressure and Direction")
        lines.append(f"          Relative Pressure = WK({k}, DeltaT, R1A{k:02d}, R2A{k:02d}, CA{k:02d}, "
                     f"{o['pc0_pa']:.17g} [Pa], {o['q_i']:.17g} [m^3 s^-1], "
                     f"{o['pv_pa']:.17g} [Pa])")
        lines.append("        END")
        lines.append("      END")
        lines.append("    END")

    # ---- WALL: Location filled in from the .msh by cfx_def_export.py ----
    wall_loc = params.get("wall_location") or ""
    lines.append(f"    BOUNDARY: {WALL_NAME}")
    lines.append("      Boundary Type = WALL")
    if wall_loc:
        lines.append(f"      Location = {wall_loc}")
    else:
        lines.append("      # Location = <wall zone of the .msh>  (cfx_def_export.py fills this in)")
    lines.append("      BOUNDARY CONDITIONS:")
    lines.append("        MASS AND MOMENTUM:")
    lines.append("          Option = No Slip Wall")
    lines.append("        END")
    lines.append("      END")
    lines.append("    END")

    lines.append("    DOMAIN MODELS:")
    lines.append("      BUOYANCY MODEL:")
    lines.append("        Option = Non Buoyant")
    lines.append("      END")
    lines.append("      DOMAIN MOTION:")
    lines.append("        Option = Stationary")
    lines.append("      END")
    lines.append("      MESH DEFORMATION:")
    lines.append("        Option = None")
    lines.append("      END")
    lines.append("      REFERENCE PRESSURE:")
    lines.append("        Reference Pressure = 1 [atm]"
                 " # All supplied pressures are gauge to this reference")
    lines.append("      END")
    lines.append("    END")
    lines.append(f"    FLUID DEFINITION: {FLUID_NAME}")
    lines.append(f"      Material = {MATERIAL_NAME}")
    lines.append("      Option = Material Library")
    lines.append("      MORPHOLOGY:")
    lines.append("        Option = Continuous Fluid")
    lines.append("      END")
    lines.append("    END")
    lines.append("    FLUID MODELS:")
    lines.append("      COMBUSTION MODEL:")
    lines.append("        Option = None")
    lines.append("      END")
    lines.append("      HEAT TRANSFER MODEL:")
    lines.append("        Option = None")
    lines.append("      END")
    lines.append("      THERMAL RADIATION MODEL:")
    lines.append("        Option = None")
    lines.append("      END")
    lines.append("      TURBULENCE MODEL:")
    lines.append("        Option = Laminar")
    lines.append("      END")
    lines.append("    END")
    # ---- INITIALISATION (domain level, as the template) ----
    lines.append("    INITIALISATION:")
    lines.append("      Option = Automatic")
    lines.append("      INITIAL CONDITIONS:")
    lines.append("        Velocity Type = Cartesian")
    lines.append("        CARTESIAN VELOCITY COMPONENTS:")
    lines.append("          Option = Automatic with Value")
    lines.append("          U = 0 [m s^-1]")
    lines.append("          V = 0 [m s^-1]")
    lines.append("          W = 0 [m s^-1]")
    lines.append("        END")
    lines.append("        STATIC PRESSURE:")
    lines.append("          Option = Automatic with Value")
    lines.append(f"          Relative Pressure = {p_init:.17e} [Pa]"
                 f" # {p_init / rbc.MMHG_TO_PA:.2f} mmHg gauge (--p-init)")
    lines.append("        END")
    lines.append("      END")
    lines.append("    END")
    lines.append("  END")  # DOMAIN

    # ---- OUTPUT CONTROL: monitors in mmHg / m^3/s ----
    lines.append("  OUTPUT CONTROL:")
    lines.append("    MONITOR OBJECTS:")
    lines.append("      MONITOR BALANCES:")
    lines.append("        Option = Full")
    lines.append("      END")
    lines.append("      MONITOR FORCES:")
    lines.append("        Option = Full")
    lines.append("      END")
    lines.append("      MONITOR PARTICLES:")
    lines.append("        Option = Full")
    lines.append("      END")
    for o in outs:
        k = o["k"]
        lines.append(f"      MONITOR POINT: P{k:02d}")
        lines.append("        Coord Frame = Coord 0")
        lines.append(f"        Expression Value = Pout{k:02d} / {MMHG_MONITOR:g}")
        lines.append("        Option = Expression")
        lines.append("      END")
    lines.append("      MONITOR POINT: Pin")
    lines.append("        Coord Frame = Coord 0")
    lines.append(f"        Expression Value = Pinlet / {MMHG_MONITOR:g}")
    lines.append("        Option = Expression")
    lines.append("      END")
    lines.append("      MONITOR POINT: Qin")
    lines.append("        Coord Frame = Coord 0")
    lines.append("        Expression Value = Qinlet")
    lines.append("        Option = Expression")
    lines.append("      END")
    for o in outs:
        k = o["k"]
        lines.append(f"      MONITOR POINT: Qoutlet{k:02d}")
        lines.append("        Coord Frame = Coord 0")
        lines.append(f"        Expression Value = Qfuture{k:02d}")
        lines.append("        Option = Expression")
        lines.append("      END")
    lines.append("      MONITOR RESIDUALS:")
    lines.append("        Option = Full")
    lines.append("      END")
    lines.append("      MONITOR TOTALS:")
    lines.append("        Option = Full")
    lines.append("      END")
    lines.append("    END")
    lines.append("    RESULTS:")
    lines.append("      File Compression Level = Default")
    lines.append("      Option = Standard")
    lines.append("    END")
    lines.append("    TRANSIENT RESULTS: Transient Results 1")
    lines.append("      File Compression Level = Default")
    lines.append("      Option = Standard")
    lines.append("      OUTPUT FREQUENCY:")
    lines.append("        Option = Time Interval")
    lines.append("        Time Interval = SaveT")
    lines.append("      END")
    lines.append("    END")
    lines.append("  END")

    # ---- SOLVER CONTROL ----
    lines.append("  SOLVER CONTROL:")
    lines.append("    ADVECTION SCHEME:")
    lines.append("      Option = High Resolution")
    lines.append("    END")
    lines.append("    CONVERGENCE CONTROL:")
    lines.append(f"      Maximum Number of Coefficient Loops = {params['max_coeff_loops']}")
    lines.append(f"      Minimum Number of Coefficient Loops = {params['min_coeff_loops']}")
    lines.append("      Timescale Control = Coefficient Loops")
    lines.append("    END")
    lines.append("    CONVERGENCE CRITERIA:")
    lines.append(f"      Residual Target = {params['residual']:g}")
    lines.append("      Residual Type = RMS")
    lines.append("    END")
    lines.append("    INTERRUPT CONTROL:")
    lines.append("      Option = Any Interrupt")
    lines.append("      CONVERGENCE CONDITIONS:")
    lines.append("        Option = Default Conditions")
    lines.append("      END")
    lines.append("    END")
    lines.append("    JUNCTION BOX ROUTINES:")
    lines.append("      Junction Box Routine List = "
                 + ",".join(r[0] for r in USER_ROUTINES if r[3]))
    lines.append("    END")
    lines.append("    TRANSIENT SCHEME:")
    lines.append("      Option = Second Order Backward Euler")
    lines.append("      TIMESTEP INITIALISATION:")
    lines.append("        Option = Automatic")
    lines.append("      END")
    lines.append("    END")
    lines.append("  END")
    lines.append("END")

    out_path = Path(out_path)
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"\n[CCL] Wrote Windkessel boundary conditions to {out_path}")
    return out_path
